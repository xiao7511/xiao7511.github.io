    raise exception 'public.is_admin() security baseline is required';
  end if;
  if pg_catalog.to_regclass('public.posts') is null or pg_catalog.to_regclass('public.profiles') is null then
    raise exception 'Community tables are required';
  end if;
end;
$$;

alter table public.posts
  add column if not exists moderation_status text not null default 'visible',
  add column if not exists moderated_at timestamptz,
  add column if not exists moderated_by uuid references auth.users(id) on delete set null;

alter table public.posts drop constraint if exists posts_moderation_status_check;
alter table public.posts
  add constraint posts_moderation_status_check
  check (moderation_status in ('visible', 'hidden', 'removed'));

create table if not exists public.user_blocks (
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint user_blocks_not_self check (blocker_id <> blocked_id)
);

create table if not exists public.post_reports (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null,
  details text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  resolution_note text,
  constraint post_reports_reason_check check (reason in ('spam', 'harassment', 'hate', 'sexual', 'violence', 'privacy', 'other')),
  constraint post_reports_details_length check (details is null or char_length(details) <= 500),
  constraint post_reports_status_check check (status in ('pending', 'reviewing', 'resolved', 'dismissed')),
  constraint post_reports_resolution_note_length check (resolution_note is null or char_length(resolution_note) <= 1000)
);

create unique index if not exists post_reports_one_pending_per_actor_idx
  on public.post_reports (post_id, reporter_id)
  where status in ('pending', 'reviewing');
create index if not exists post_reports_queue_idx on public.post_reports (status, created_at);

create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  report_id bigint references public.post_reports(id) on delete set null,
  post_id bigint not null references public.posts(id) on delete cascade,
  moderator_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  note text,
  created_at timestamptz not null default now(),
  constraint moderation_actions_action_check check (action in ('dismiss', 'hide', 'remove', 'restore')),
  constraint moderation_actions_note_length check (note is null or char_length(note) <= 1000)
);

create index if not exists moderation_actions_post_idx on public.moderation_actions (post_id, created_at desc);

create table if not exists public.account_deletion_requests (
  user_id uuid primary key,
  status text not null default 'requested',
  requested_at timestamptz not null default now(),
  cancelled_at timestamptz,
  completed_at timestamptz,
  processing_note text,
  constraint account_deletion_status_check check (status in ('requested', 'processing', 'cancelled', 'completed')),
  constraint account_deletion_note_length check (processing_note is null or char_length(processing_note) <= 1000)
);

alter table public.user_blocks enable row level security;
alter table public.post_reports enable row level security;
alter table public.moderation_actions enable row level security;
alter table public.account_deletion_requests enable row level security;

revoke all on table public.user_blocks, public.post_reports, public.moderation_actions, public.account_deletion_requests from public, anon, authenticated;
grant select on table public.user_blocks, public.post_reports, public.account_deletion_requests to authenticated;
grant select on table public.moderation_actions to authenticated;

drop policy if exists "blocks owner read" on public.user_blocks;
create policy "blocks owner read" on public.user_blocks for select to authenticated
using (blocker_id = auth.uid() or public.is_admin());

drop policy if exists "reports owner or admin read" on public.post_reports;
create policy "reports owner or admin read" on public.post_reports for select to authenticated
using (reporter_id = auth.uid() or public.is_admin());

drop policy if exists "moderation admin read" on public.moderation_actions;
create policy "moderation admin read" on public.moderation_actions for select to authenticated
using (public.is_admin());

drop policy if exists "deletion request owner or admin read" on public.account_deletion_requests;
create policy "deletion request owner or admin read" on public.account_deletion_requests for select to authenticated
using (user_id = auth.uid() or public.is_admin());

drop policy if exists "posts public read" on public.posts;
create policy "posts visible read" on public.posts for select
using (
  user_id = auth.uid()
  or public.is_admin()
  or (
    moderation_status = 'visible'
    and (
      auth.uid() is null
      or user_id is null
      or not exists (
        select 1 from public.user_blocks
        where blocker_id = auth.uid() and blocked_id = posts.user_id
      )
    )
  )
);

-- Prevent post owners from changing identity, hierarchy or moderation columns.
