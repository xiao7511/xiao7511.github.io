create or replace function public.report_post(p_post_id bigint, p_reason text, p_details text default null)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  current_user_id uuid := auth.uid();
  report_id bigint;
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_reason is null or p_reason not in ('spam', 'harassment', 'hate', 'sexual', 'violence', 'privacy', 'other') then
    raise exception 'Invalid report reason' using errcode = '22023';
  end if;
  if p_details is not null and char_length(btrim(p_details)) > 500 then
    raise exception 'Report details are too long' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.posts
    where id = p_post_id and moderation_status = 'visible' and user_id is distinct from current_user_id
  ) then
    raise exception 'Post is unavailable for reporting' using errcode = 'P0002';
  end if;

  insert into public.post_reports (post_id, reporter_id, reason, details)
  values (p_post_id, current_user_id, p_reason, nullif(btrim(p_details), ''))
  on conflict (post_id, reporter_id) where status in ('pending', 'reviewing')
  do update set reason = excluded.reason, details = excluded.details, created_at = now()
  returning id into report_id;
  return report_id;
end;
$$;

create or replace function public.set_user_block(p_blocked_id uuid, p_blocked boolean default true)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_blocked_id is null or p_blocked is null or p_blocked_id = current_user_id then
    raise exception 'Invalid blocked user' using errcode = '22023';
  end if;
  if not exists (select 1 from auth.users where id = p_blocked_id) then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  if p_blocked then
    insert into public.user_blocks (blocker_id, blocked_id)
    values (current_user_id, p_blocked_id)
    on conflict (blocker_id, blocked_id) do nothing;
  else
    delete from public.user_blocks where blocker_id = current_user_id and blocked_id = p_blocked_id;
  end if;
  return p_blocked;
end;
$$;

create or replace function public.request_account_deletion()
returns timestamptz
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  current_user_id uuid := auth.uid();
  requested timestamptz := now();
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  insert into public.account_deletion_requests (user_id, status, requested_at, cancelled_at, completed_at, processing_note)
  values (current_user_id, 'requested', requested, null, null, null)
  on conflict (user_id) do update
  set status = 'requested', requested_at = excluded.requested_at, cancelled_at = null, completed_at = null, processing_note = null;
  return requested;
end;
$$;

create or replace function public.cancel_account_deletion_request()
returns boolean
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  update public.account_deletion_requests
  set status = 'cancelled', cancelled_at = now()
  where user_id = current_user_id and status = 'requested';
  return found;
end;
$$;

create or replace function public.review_post_report(p_report_id bigint, p_action text, p_note text default null)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  moderator uuid := auth.uid();
  target_post bigint;
begin
  if moderator is null or not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_action is null or p_action not in ('dismiss', 'hide', 'remove', 'restore') then
    raise exception 'Invalid moderation action' using errcode = '22023';
  end if;
  if p_note is not null and char_length(btrim(p_note)) > 1000 then
    raise exception 'Moderation note is too long' using errcode = '22023';
  end if;

  select post_id into target_post from public.post_reports where id = p_report_id for update;
  if target_post is null then
    raise exception 'Report not found' using errcode = 'P0002';
  end if;

  if p_action = 'hide' then
    update public.posts set moderation_status = 'hidden', moderated_at = now(), moderated_by = moderator where id = target_post;
  elsif p_action = 'remove' then
    update public.posts set moderation_status = 'removed', moderated_at = now(), moderated_by = moderator where id = target_post;
  elsif p_action = 'restore' then
    update public.posts set moderation_status = 'visible', moderated_at = now(), moderated_by = moderator where id = target_post;
  end if;

  update public.post_reports
  set status = case when p_action = 'dismiss' then 'dismissed' else 'resolved' end,
      reviewed_at = now(), reviewed_by = moderator, resolution_note = nullif(btrim(p_note), '')
  where id = p_report_id;

  insert into public.moderation_actions (report_id, post_id, moderator_id, action, note)
  values (p_report_id, target_post, moderator, p_action, nullif(btrim(p_note), ''));
end;
$$;

